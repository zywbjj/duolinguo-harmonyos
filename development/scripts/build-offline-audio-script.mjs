import { readFileSync, writeFileSync } from 'node:fs';
const source = readFileSync(new URL('../overlay/entry/src/main/resources/rawfile/voice/duo-offline-speech.js', import.meta.url), 'utf8');
const stages = ['idle', 'model-loading', 'model-ready', 'capture-starting', 'capture-started', 'capture-stopped', 'capture-interrupted',
  'capture-denied', 'capture-error', 'model-error', 'engine-error', 'engine-unsupported', 'engine-overloaded',
  'language-unsupported', 'no-speech'];
const output = `// Generated by scripts/build-offline-audio-script.mjs from the reviewed rawfile JS.\n` +
  `export function webAudioScript(): string {\n  return ${JSON.stringify(source)};\n}\n\n` +
  `export function audioStatusScript(): string {\n  return ${JSON.stringify("JSON.stringify(window.__duoAudioV2 ? {sequence:window.__duoAudioV2.sequence,stage:window.__duoAudioV2.stage} : {sequence:0,stage:'unavailable'})")};\n}\n\n` +
  `export function audioStage(message: string): string {\n  const stages: string[] = ${JSON.stringify(stages)};\n` +
  `  return stages.indexOf(message) >= 0 ? message : '';\n}\n\n` +
  `export class AudioStatus { sequence: number = -1; stage: string = ''; }\n` +
  `export function parseAudioStatus(raw: string): AudioStatus {\n` +
  `  try {\n    if (raw.length > 512) { return new AudioStatus(); }\n` +
  `    let value: AudioStatus | string = JSON.parse(raw) as AudioStatus | string;\n` +
  `    if (typeof value === 'string') { value = JSON.parse(value) as AudioStatus; }\n` +
  `    if (value && typeof value === 'object' && Number.isInteger(value.sequence) && value.sequence >= 0 &&\n` +
  `      value.sequence < 1000000000 && typeof value.stage === 'string' && audioStage(value.stage) !== '') { return value; }\n` +
  `  } catch {}\n  return new AudioStatus();\n}\n`;
writeFileSync(new URL('../overlay/entry/src/main/ets/services/WebAudioScript.ets', import.meta.url), output);
